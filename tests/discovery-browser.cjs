'use strict';
const { chromium }=require('playwright');
const { AxeBuilder }=require('@axe-core/playwright');
const fs=require('node:fs'),assert=require('node:assert/strict');
const origin='http://127.0.0.1:8081/ai-agent-use-cases/';
(async()=>{
 const browser=await chromium.launch();
 fs.mkdirSync('qa-artifacts',{recursive:true});
 const audits=[];
 for(const [name,width,height] of [['desktop',1440,1000],['mobile',390,844],['small-mobile',320,740]]){
  const context=await browser.newContext({viewport:{width,height},reducedMotion:'reduce'});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.locator('#drawn-case .card').waitFor();
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'qa-artifacts/after-'+name+'.jpg',type:'jpeg',quality:70});
  await page.locator('.discovery-layout').screenshot({path:'qa-artifacts/guide-'+name+'.png'});
  if(name!=='small-mobile')console.log('VISUAL:after-'+name+':'+fs.readFileSync('qa-artifacts/after-'+name+'.jpg').toString('base64'));
  // Journey 1: choose a need, draw without repeats, read and return using the keyboard.
  await page.locator('[data-scenario="省錢"]').click();
  if(width<=760)await page.waitForFunction(()=>{const r=document.getElementById('draw-title').getBoundingClientRect();return r.top>=0&&r.bottom<innerHeight;});
  assert.equal(await page.locator('#scenario').inputValue(),'省錢');
  assert.equal(await page.locator('[data-scenario="省錢"]').getAttribute('aria-pressed'),'true');
  const first=await page.locator('#drawn-case h3').innerText();
  await page.locator('#draw-case').click();
  assert.notEqual(await page.locator('#drawn-case h3').innerText(),first);
  const read=page.locator('#drawn-case .card-bottom button');
  await read.focus();await page.keyboard.press('Enter');
  await page.locator('#detail[open]').waitFor();
  assert.match(await page.locator('#detail-title').innerText(),/\S/);
  await page.locator('.research-details summary').click();
  assert.match(await page.locator('.markdown a').first().getAttribute('href'),/^https?:/);
  await page.screenshot({path:'qa-artifacts/detail-'+name+'.png'});
  await page.keyboard.press('Escape');
  assert.equal(await read.evaluate(el=>document.activeElement===el),true);
  assert.equal(new URL(page.url()).searchParams.get('scenario'),'省錢');
  // Journey 2: combine search and filters, recover from no results.
  await page.locator('#reset').click();
  await page.locator('#query').fill('旅遊');
  await page.locator('#scenario').selectOption('生活');
  await page.locator('#tool').selectOption('Grok Bot');
  await page.locator('#category').selectOption('旅遊／消費研究');
  await page.locator('#proof').selectOption('作者報告／示範');
  assert((await page.locator('#results .card').count())>0);
  await page.locator('#query').fill('no-matching-case-123');
  assert.equal(await page.locator('#empty').isVisible(),true);
  assert.equal(await page.locator('#draw-case').isDisabled(),true);
  await page.locator('#empty-reset').click();
  assert.equal(await page.locator('#draw-case').isEnabled(),true);
  await page.locator('#kind').selectOption('pending');
  assert.equal(await page.locator('#drawn-case .card').count(),0);
  assert((await page.locator('#results .card').count())>0);
  await page.locator('#reset').click();
  const resultTrigger=page.locator('#results .card .card-bottom button').first();
  const resultId=await page.locator('#results .card').first().getAttribute('data-case-id');
  await resultTrigger.click();await page.goBack();
  assert.equal(await page.evaluate(()=>document.activeElement.closest('.card')?.dataset.caseId),resultId);
  assert.equal(await page.evaluate(()=>document.activeElement.closest('#results')?.id),'results');
  // Journey 3: open a shareable direct link under the GitHub Pages base path.
  await page.goto(origin+'?scenario=生活&q=旅遊&case=UC-001',{waitUntil:'networkidle'});
  await page.locator('#detail[open]').waitFor();
  assert.match(await page.locator('#detail-title').innerText(),/交通和住宿/);
  await page.reload({waitUntil:'networkidle'});
  await page.locator('#detail[open]').waitFor();
  await page.locator('#close-detail').click();
  assert.equal(await page.locator('#scenario').inputValue(),'生活');
  assert.equal(await page.locator('#query').inputValue(),'旅遊');
  await page.locator('#drawn-case .card-bottom button').click();
  await page.goBack();
  assert.equal(await page.locator('#detail').evaluate(el=>el.open),false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'no horizontal page overflow');
  await page.locator('#reset').click();
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  audits.push({viewport:name,violations:audit.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))});
  assert.equal(audit.violations.length,0,JSON.stringify(audits[audits.length-1]));
  assert.deepEqual(errors,[]);
  console.log('PASS BROWSER '+name+': guided discovery, shuffle, keyboard, combined filters, empty recovery, pending exclusion, direct links, refresh, back, overflow; axe violations='+audit.violations.length);
  await context.close();
 }
 const page=await browser.newPage();
 await page.route('**/catalog.json',route=>route.fulfill({status:503,body:'unavailable'}));
 await page.goto(origin,{waitUntil:'networkidle'});
 assert.equal(await page.locator('#error').isVisible(),true);
 assert.equal(await page.locator('#draw-case').isDisabled(),true);
 await page.unroute('**/catalog.json');
 await page.locator('#retry').click();
 await page.locator('#drawn-case .card').waitFor();
 await page.route('**/catalog.json',route=>route.fulfill({contentType:'application/json',body:'{"files":[]}'}));
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('#error').isVisible(),true);
 assert.equal(await page.locator('[data-scenario]').first().isDisabled(),true);
 console.log('PASS BROWSER: network failure, retry recovery and empty catalog');
 fs.writeFileSync('qa-artifacts/accessibility.json',JSON.stringify(audits,null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
