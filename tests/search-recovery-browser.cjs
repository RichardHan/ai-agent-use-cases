'use strict';
const sourceRoute=require('./source-route.cjs');
const {ensureFiltersVisible}=require('./filter-controls.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {AxeBuilder} = require('@axe-core/playwright');
module.exports = async function searchRecovery({browser, origin, observe=false,prefix='search',sizes=[['desktop',1440,1000],['mobile',390,844],['small-mobile',320,740]]}) {
  const report=[];
  fs.mkdirSync('qa-artifacts',{recursive:true});
  for (const [name,width,height] of sizes) {
    const context=await browser.newContext({viewport:{width,height},reducedMotion:'reduce'});
    const page=await context.newPage();
    const started=Date.now();
    await page.goto(origin,{waitUntil:'networkidle'});
    await page.locator('#results .card').first().waitFor();
    const navigationAndReadyMs=Date.now()-started;
    await page.locator('#query').fill('旅遊');
    await ensureFiltersVisible(page);
    await page.locator('#tool').selectOption('Grok Bot');
    await ensureFiltersVisible(page);
    await page.locator('#category').selectOption('旅遊／消費研究');
    await ensureFiltersVisible(page);
    await page.locator('#proof').selectOption('作者報告／示範');
    const matching=await page.locator('#results .card').count();
    assert(matching>0);
    await ensureFiltersVisible(page);
    await page.locator('#scenario').selectOption('開發');
    assert.equal(await page.locator('#empty').isVisible(),true);
    await page.locator('#results-count').scrollIntoViewIfNeeded();
    await page.screenshot({path:'qa-artifacts/'+prefix+'-'+(observe?'before-':'after-')+name+'.jpg',type:'jpeg',quality:75});
    console.log('VISUAL:'+prefix+'-'+(observe?'before-':'after-')+name+':'+fs.readFileSync('qa-artifacts/'+prefix+'-'+(observe?'before-':'after-')+name+'.jpg').toString('base64'));
    const row={viewport:name,navigationAndReadyMs,matchingBeforeScenario:matching,empty:await page.locator('#empty').innerText(),activeFilters:await page.locator('#active-filters button').count()};
    if (observe) {
      await page.locator('#empty-reset').click();
      row.queryAfterReset=await page.locator('#query').inputValue();
      report.push(row);
      await context.close();
      continue;
    }
    // Journey 1: recover from an incompatible combination without losing the task.
    assert.equal(await page.locator('#active-filters [data-remove-filter]').count(),5);
    const suggestion=page.locator('#empty-suggestions [data-remove-filter="scenario"]');
    assert.equal(await suggestion.count(),1,'offer a precise, nonzero relaxation');
    assert.match(await suggestion.innerText(),new RegExp(String(matching)+' 筆'));
    const recoveryStarted=Date.now();
    await suggestion.focus();await page.keyboard.press('Enter');
    row.keyboardRecoveryMs=Date.now()-recoveryStarted;
    assert.equal(await page.locator('#results .card').count(),matching);
    assert.equal(await page.locator('#query').inputValue(),'旅遊');
    assert.equal(await page.locator('#category').inputValue(),'旅遊／消費研究');
    assert.equal(await page.locator('#tool').inputValue(),'Grok Bot');
    assert.equal(await page.locator('#proof').inputValue(),'作者報告／示範');
    assert.equal(new URL(page.url()).searchParams.has('scenario'),false);
    assert.equal(await page.locator('#results-count').evaluate(n=>document.activeElement===n),true);
    // Journey 2: share a filtered result, read a case, and return to the same intent.
    const filteredURL=page.url();
    const id=await page.locator('#results .card').first().getAttribute('data-case-id');
    await page.locator('#results .card .card-bottom button').first().click();
    await page.locator('#detail[open]').waitFor();
    const directURL=page.url();
    await page.reload({waitUntil:'networkidle'});
    await page.locator('#detail[open]').waitFor();
    assert.equal(new URL(directURL).searchParams.get('case'),id);
    await page.locator('#close-detail').click();
    assert.equal(page.url(),filteredURL);
    assert.equal(await page.locator('#active-filters [data-remove-filter]').count(),4);
    const trigger=page.locator('#results .card .card-bottom button').first();
    await trigger.click();await page.goBack();
    assert.equal(await trigger.evaluate(n=>document.activeElement===n),true);
    await page.locator('#active-filters [data-remove-filter="tool"]').click();
    assert.equal(await page.locator('#tool').inputValue(),'');
    assert.equal(await page.locator('#query').inputValue(),'旅遊');
    assert.equal(await page.locator('#category').inputValue(),'旅遊／消費研究');
    const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
    row.axeViolations=audit.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}));
    assert.deepEqual(row.axeViolations,[]);
    // A failed AND query can retain the original task and all selected facets.
    await page.locator('#query').fill('旅遊 xyz987');
    assert.equal(await page.locator('#empty').isVisible(),true);
    const shorter=page.locator('#empty-suggestions button').filter({hasText:'只移除關鍵字「xyz987」'});
    assert.equal(await shorter.count(),1);
    const recoveredCount=Number((await shorter.innerText()).match(/查看 (\d+) 筆/)[1]);
    assert(recoveredCount>0);
    const remainingCategory=await page.locator('#category').inputValue();
    await shorter.focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator('#query').inputValue(),'旅遊');
    assert.equal(await page.locator('#category').inputValue(),remainingCategory);
    assert.equal(new URL(page.url()).searchParams.get('q'),'旅遊');
    assert.equal(await page.locator('#results .card').count(),recoveredCount);
    assert.equal(await page.locator('#results-count').evaluate(n=>document.activeElement===n),true);
    await page.locator('#query').fill('xyz987');
    assert.equal(await page.locator('#empty-suggestions button').filter({hasText:'只移除關鍵字'}).count(),0);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    // Journey 3: a genuinely unknown query is preserved when clearing only facets.
    await page.locator('#query').fill('找不到的任務xyz987');
    assert.equal(await page.locator('#empty').isVisible(),true);
    await page.locator('#clear-facets').click();
    assert.equal(await page.locator('#query').inputValue(),'找不到的任務xyz987');
    assert.equal(await page.locator('#category').inputValue(),'');
    assert.equal(await page.locator('#proof').inputValue(),'');
    assert.equal(await page.locator('#empty').isVisible(),true);
    assert.equal(await page.locator('#empty-suggestions [data-remove-filter]').count(),0);
    await page.locator('#edit-query').click();
    assert.equal(await page.locator('#query').evaluate(n=>document.activeElement===n),true);
    await page.locator('#query').fill('很長的搜尋關鍵字'.repeat(30)+' <img src=x onerror=alert(1)>');
    assert.equal(await page.locator('#active-filters img').count(),0);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    const emptyAudit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
    assert.equal(emptyAudit.violations.length,0,JSON.stringify(emptyAudit.violations));
    await page.locator('#active-filters [data-remove-filter="query"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#active-filters').isVisible(),false);
    assert.equal(await page.locator('#empty').isVisible(),false);
    assert.equal(await page.locator('#results-count').evaluate(n=>document.activeElement===n),true);
    await page.locator('#query').fill('xyz987');
    await page.locator('#empty-reset').click();
    assert.equal(await page.locator('#query').inputValue(),'');
    // A tool already named in a conversational question is an explicit recovery,
    // not an automatic query rewrite or a claim that every hit solves the task.
    for(const question of ['我想用Linear準備每天站會','How can I use Linear to prepare for a team meeting?']){
      const params=new URLSearchParams({q:question,scenario:'工作',kind:'case',tool:'Grok Bot',scope:'overview'});
      await page.goto(origin+'?'+params,{waitUntil:'networkidle'});
      await page.locator('#empty').waitFor();
      assert.equal(await page.locator('#query').inputValue(),question);
      const namedTool=page.locator('#empty-suggestions [data-query-recovery="linear"]');
      await namedTool.waitFor();
      assert.match(await namedTool.innerText(),/原問題提到「linear」/);
      const expectedCount=Number((await namedTool.innerText()).match(/搜尋 (\d+) 筆文字命中/)[1]);
      assert(expectedCount>0);
      await namedTool.focus();await page.keyboard.press('Enter');
      assert.equal(await page.locator('#query').inputValue(),'linear');
      assert.equal(await page.locator('#results .card').count(),expectedCount);
      assert.equal(await page.locator('#results .card[data-case-id="UC-408"]').count(),1);
      assert.equal(await page.locator('#results-count').evaluate(n=>document.activeElement===n),true);
      const recoveredURL=new URL(page.url());
      for(const key of ['scenario','kind','tool','scope'])assert.equal(recoveredURL.searchParams.get(key),params.get(key));
      assert.equal(recoveredURL.searchParams.get('q'),'linear');
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
      await page.reload({waitUntil:'networkidle'});
      await page.locator('#results .card').first().waitFor();
      assert.equal(await page.locator('#query').inputValue(),'linear');
      assert.equal(await page.locator('#results .card[data-case-id="UC-408"]').count(),1);
    }
    row.passed=true;report.push(row);
    await context.close();
  }

  if(!observe&&prefix==='search'){
    const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
    const page=await context.newPage();
    let release;
    const gate=new Promise(resolve=>{release=resolve;});
    await page.route('**/catalog.json',async route=>{await gate;await route.continue();});
    await page.goto(origin+'?q=旅遊&scenario=開發',{waitUntil:'domcontentloaded'});
    assert.equal(await page.locator('#search-feedback').isVisible(),false,'loading is not empty results');
    assert.equal(await page.locator('#empty').isVisible(),false);
    release();await page.locator('#search-feedback').waitFor();await page.unroute('**/catalog.json');
    await page.route('**/catalog.json',route=>route.fulfill({status:503,body:'unavailable'}));
    await page.reload({waitUntil:'networkidle'});
    assert.equal(await page.locator('#error').isVisible(),true);
    assert.equal(await page.locator('#search-feedback').isVisible(),false);
    assert.equal(await page.locator('#empty').isVisible(),false);
    await page.unroute('**/catalog.json');await page.locator('#retry').click();
    await page.locator('#search-feedback').waitFor();
    await page.goto(origin+'?q=旅遊&scenario=未分類情境',{waitUntil:'networkidle'});
    assert.match(await page.locator('#active-filters [data-remove-filter="scenario"]').innerText(),/未分類情境/);
    await page.locator('#active-filters [data-remove-filter="scenario"]').click();
    assert.equal(await page.locator('#query').inputValue(),'旅遊');
    assert((await page.locator('#results .card').count())>0);
    await sourceRoute(page,'**/cases/001-travel-checkout.md',route=>route.fulfill({status:404,body:'not found'}));
    await page.goto(origin+'?q=旅遊&tool=Grok%20Bot&category='+encodeURIComponent('旅遊／消費研究')+'&proof='+encodeURIComponent('作者報告／示範'),{waitUntil:'networkidle'});
    const loadedMatches=await page.locator('#results .card').count();
    assert(loadedMatches>0);
    assert.match(await page.locator('#results-count').innerText(),/1 個來源檔案未載入/);
    await ensureFiltersVisible(page);
    await page.locator('#scenario').selectOption('開發');
    const suggestion=page.locator('#empty-suggestions [data-remove-filter="scenario"]');
    assert.match(await suggestion.innerText(),new RegExp(loadedMatches+' 筆'));
    assert.match(await page.locator('#empty-hint').innerText(),/部分條目載入失敗/);
    await suggestion.click();
    assert.equal(await page.locator('#results .card').count(),loadedMatches);
    await page.locator('#query').fill('旅遊 xyz987');
    const queryOption=page.locator('#empty-suggestions [data-query-recovery="旅遊"]');
    let releaseRetry;
    const retryGate=new Promise(resolve=>{releaseRetry=resolve;});
    await page.route('**/cases/001-travel-checkout.md',async route=>{
      await retryGate;
      await route.fulfill({status:404,body:'not found'});
    });
    await page.locator('#retry-failed').click();
    await queryOption.focus();
    releaseRetry();
    await page.waitForFunction(()=>document.querySelector('#retry-failed').getAttribute('aria-disabled')==='false');
    assert.equal(await queryOption.evaluate(n=>document.activeElement===n),true,'retry preserves the surviving query suggestion focus');
    await context.close();
    console.log('PASS SEARCH STATES: loading, error/retry, unknown scenario, partial corpus counts');
  }

  fs.writeFileSync('qa-artifacts/'+prefix+'-'+(observe?'baseline':'verification')+'.json',JSON.stringify(report,null,2));
  console.log('SEARCH_RECOVERY '+prefix+' '+JSON.stringify(report));
};
