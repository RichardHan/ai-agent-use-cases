'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const origin=process.env.ROUND_URL||'http://127.0.0.1:8081/ai-agent-use-cases/';
(async()=>{
  const browser=await chromium.launch();
  try{
    for(const width of [390,1440]){
      const page=await browser.newPage({viewport:{width,height:844}});
      try{
        await page.goto(new URL('?q=旅遊&scenario=生活#explore',origin).href,{waitUntil:'networkidle'});
        await page.locator('#results .card').first().waitFor();
        const before=await page.locator('#results .card').evaluateAll(nodes=>nodes.map(node=>node.dataset.caseId));
        await page.locator('#query').fill('郵件');
        await page.locator('#search-submit').click();
        const submitted=page.url();
        assert.equal(new URL(submitted).searchParams.get('q'),'郵件');
        await page.goBack();
        assert.equal(await page.locator('#query').inputValue(),'旅遊');
        assert.equal(await page.locator('#scenario').inputValue(),'生活');
        assert.deepEqual(await page.locator('#results .card').evaluateAll(nodes=>nodes.map(node=>node.dataset.caseId)),before);
        await page.goForward();
        assert.equal(page.url(),submitted);
        assert.equal(await page.locator('#query').inputValue(),'郵件');
        const beforeFacet=page.url();
        if(!await page.locator('#filter-options').evaluate(node=>node.open))await page.locator('#filter-summary').click();
        await page.locator('#kind').selectOption('case');
        await page.locator('#difficulty').selectOption('入門對話');
        await page.locator('#sort').selectOption('reviewed');
        const filtered=page.url();
        assert.notEqual(filtered,beforeFacet);
        await page.goBack();
        assert.equal(page.url(),beforeFacet,'Back from live filters restores the committed search');
        assert.equal(await page.locator('#kind').inputValue(),'');
        assert.equal(await page.locator('#difficulty').inputValue(),'');
        assert.equal(await page.locator('#sort').inputValue(),'');
        await page.goForward();
        assert.equal(page.url(),filtered,'Forward restores all live filters as one history entry');
        await page.locator('#search-submit').click();
        await page.goBack();
        assert.equal(page.url(),beforeFacet);
        assert.equal(await page.locator('#kind').inputValue(),'');
        assert.equal(await page.locator('#difficulty').inputValue(),'');
        assert.equal(await page.locator('#sort').inputValue(),'');
        await page.goForward();
        assert.equal(page.url(),filtered);
        assert.equal(await page.locator('#kind').inputValue(),'case');
        assert.equal(await page.locator('#difficulty').inputValue(),'入門對話');
        assert.equal(await page.locator('#sort').inputValue(),'reviewed');
        await page.reload({waitUntil:'networkidle'});
        assert.equal(await page.locator('#kind').inputValue(),'case');
        assert.equal(await page.locator('#difficulty').inputValue(),'入門對話');
        assert.equal(await page.locator('#sort').inputValue(),'reviewed');
        await page.locator('#results .card h3 button').first().click();
        assert(await page.locator('#detail').evaluate(node=>node.open));
        await page.goBack();
        assert.equal(await page.locator('#detail').evaluate(node=>node.open),false);
        assert.equal(page.url(),filtered);
        await page.locator('#query').fill('不存在xyz987');
        assert(await page.locator('#empty').isVisible());
        if(!await page.locator('#filter-options').evaluate(node=>node.open))await page.locator('#filter-summary').click();
        const experience=page.locator('.chip[data-kind="evidence"]');
        await experience.focus();
        await page.keyboard.press('Space');
        assert.equal(await page.locator('#query').inputValue(),'不存在xyz987');
        assert.equal(await page.locator('#kind').inputValue(),'evidence');
        assert(await page.locator('#empty').isVisible());
        assert.equal(await page.evaluate(()=>document.activeElement.id),'results-count');
        const resultBounds=await page.locator('#results-count').boundingBox();
        assert(resultBounds&&resultBounds.y>=0&&resultBounds.y<844);
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
        await page.goto(origin,{waitUntil:'networkidle'});
        if(!await page.locator('#filter-options').evaluate(node=>node.open))await page.locator('#filter-summary').click();
        await page.locator('#difficulty').selectOption('入門對話');
        await page.locator('#recent-entry').click();
        const recent=page.url();
        await page.locator('#query').fill('旅遊');
        await page.locator('#search-submit').click();
        await page.goBack();
        assert.equal(page.url(),recent);
        assert.equal(await page.locator('#sort').inputValue(),'reviewed');
        assert.equal(await page.locator('#query').inputValue(),'');
        console.log(`SEARCH_HISTORY_PASS width=${width}`);
      }finally{await page.close();}
    }
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
